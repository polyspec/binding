export interface GoScope {
  model: Model;
  module: string;
  imports: Set<string>;
  // Whether the package names the ordered map of T-2, which it declares as an alias of binding.Map.
  usesMap?: boolean;
  // Whether the package names the keyed map of T-2 and its Key.
  usesKeyed?: boolean;
  // GN-16: the arities of the tuples of different part types that the package names, as Tuple<N>.
  usesTuples?: Set<number>;
  // U-7, GN-15c: the classes of the package whose instances the out rows of a value alias make, which aliasInstance
  // makes by their numbers.
  aliasInstances?: Set<ObjectClass>;
  // GN-15a: the classes and callbacks of other modules that the package reaches through binding.Token.
  reaches?: Set<string>;
  // GN-15f: the import paths of the packages of other repositories that the package names, each with its name.
  foreignImports?: Map<string, string>;
  // GN-6s, GN-15d: the import paths of the packages errors of other repositories, each with the name that the import
  // gives it, because its package name errors is that of the standard package.
  foreignErrors?: Map<string, string>;
  // GN-6s: the callback units of other repositories that the package encodes, each with a dispatch of the package.
  foreignCallbacks?: Set<CallbackUnit>;
  // Whether a body keeps an instance alive after its call (runtime.KeepAlive) or returns an iterator (iter).
  usesRuntime?: boolean;
  usesJson?: boolean;
  usesIter?: boolean;
}

function goUnitName(scope: GoScope, unit: Unit): string {
  if (unit.module === scope.module) return goName(unit.name);
  scope.imports.add(unit.module);
  return `${goPackage(scope.model.contract, unit.module)}.${goName(unit.name)}`;
}

export const callbackOf = (model: Model, type: Type): CallbackUnit | undefined => {
  const library = libraryOf(type);
  // GN-6s: a callback unit of another repository, which a parameter takes.
  if (library !== undefined) return model.foreignCallbacks.find((c) => c.library === library && c.unit.id === (type as { unit: string }).unit);
  const unit = unitOf(model, type);
  return unit === undefined ? undefined : model.callbacks.find((c) => c.unit === unit);
};

// GN-15a: a class or a callback of another module, which the package reaches through the functions of the package of
// that module that take binding.Token; undefined for one of this module.
function reached(scope: GoScope, unit: Unit): string | undefined {
  if (unit.module === scope.module) return undefined;
  (scope.reaches ??= new Set()).add(unit.id);
  scope.imports.add(unit.module);
  return goPackage(scope.model.contract, unit.module);
}

// U-7, GN-15c: only the package of a class makes its instance by the number of the class.
function sameModule(scope: GoScope, unit: Unit, what: string): void {
  if (unit.module !== scope.module) throw new Unsupported(`${unit.id}: a ${what} of the module ${unit.module || '(the root)'} in the module ${scope.module || '(the root)'} is not generated for Go yet (its handle and dispatch are unexported)`);
}

// Whether a type names a unit, inside another type too.
const namesUnit = (type: Type): boolean => {
  if (typeof type === 'string') return false;
  if ('unit' in type) return true;
  return [...('tuple' in type ? type.tuple : []), ...['list', 'optional', 'map', 'keyed_map'].flatMap((key) => (key in type ? [(type as Record<string, Type>)[key] as Type] : []))].some(namesUnit);
};

export function goType(scope: GoScope, type: Type): string {
  if (typeof type === 'string') {
    // T-1: a source is a []byte, which holds the bytes of any Go string ([]byte(s)).
    const base: Record<string, string> = { bool: 'bool', int: 'int64', int64: 'int64', uint: 'uint64', float: 'float64', text: 'string', latin1: 'string', bytes: '[]byte', source: '[]byte', path: 'string' };
    const found = base[type];
    if (found === undefined) throw new Unsupported(`the type ${type} is not generated for Go yet`);
    return found;
  }
  if ('list' in type) return `[]${goType(scope, type.list)}`;
  if ('map' in type) {
    // T-2: an ordered map, not a Go map, whose iteration order is random.
    scope.usesMap = true;
    return `*Map[${goType(scope, type.map)}]`;
  }
  if ('keyed_map' in type) {
    scope.usesKeyed = true;
    return `*KeyedMap[${goType(scope, type.keyed_map)}]`;
  }
  // GN-15e: a pointer whose nil is no value of its type takes no second pointer.
  if ('optional' in type) return `${nilAbsent(scope.model, type.optional) ? '' : '*'}${goType(scope, type.optional)}`;
  // GN-6ae: a function is a Go func that returns any value and an error, and a passthrough is any value, because a
  // method of Go has no type parameter.
  if ('function' in type) {
    const parts = type.function.parameters.map((part) => goType(scope, part)).join(', ');
    if (machineFunction(type)) return `func(${parts}) (any, error)`;
    // GN-6z: a function that the core may keep returns its result and an error, and the error alone for none.
    return type.function.returns === 'none' ? `func(${parts}) error` : `func(${parts}) (${goType(scope, type.function.returns)}, error)`;
  }
  if ('passthrough' in type) return 'any';
  if ('tuple' in type) {
    // T-2, GN-16: a tuple inside another type or as a parameter is a Go array of its one part type, else a struct of
    // its parts in order (a Go array has one element type).
    const parts = type.tuple.map((t) => goType(scope, t));
    if (tupleArray(parts)) return `[${parts.length}]${parts[0] ?? ''}`;
    (scope.usesTuples ??= new Set()).add(parts.length);
    return `Tuple${parts.length}[${parts.join(', ')}]`;
  }
  // GN-6x: a value class of another repository is the pointer to the Go type of the owner's class.
  const valueClass = aliasOf(scope.model, type);
  if (valueClass?.owner !== undefined) {
    const owner = valueClass.owner;
    const pkg = goPackage(owner, valueClass.unit.module);
    if (new Set(scope.model.contract.units.map((u) => goPackage(scope.model.contract, u.module))).has(pkg)) throw new Unsupported(`${owner.library}.${valueClass.unit.id}: the Go package ${pkg} of the value class has the name of a package of ${scope.model.contract.library} (GN-6x)`);
    (scope.foreignImports ??= new Map()).set(goImport(owner, valueClass.unit.module), pkg);
    return `*${pkg}.${goName(valueClass.unit.name)}`;
  }
  // U-7: a value of a value alias, of this repository or another, is any Go value; its core judges it.
  if (valueClass !== undefined) return 'any';
  const object = objectUnit(scope.model, type);
  if (object !== undefined) return `*${goUnitName(scope, object.unit)}`;
  const callback = callbackOf(scope.model, type);
  if (callback !== undefined) return callback.library === undefined ? goUnitName(scope, callback.unit) : foreignCallbackType(scope, callback);
  const iface = interfaceOf(scope.model, type);
  if (iface !== undefined) return interfacePackage(scope, iface);
  const library = libraryOf(type);
  if (library !== undefined) {
    // GN-15f: a record of another repository is the struct of the package of its module in the Go module of that
    // repository, which go.mod requires.
    const record = unitOf(scope.model, type);
    const owner = scope.model.foreign.get(library);
    if (record?.kind !== 'record' || owner === undefined) throw new Unsupported(`${library}.${(type as { unit: string }).unit}: a unit of another repository other than a value alias or a record is not generated for Go yet`);
    if ((record.fields ?? []).some((f) => namesUnit(f.type))) throw new Unsupported(`${library}.${record.id}: a record of another repository with a field of a unit type is not generated for Go yet (GN-15f)`);
    const pkg = goPackage(owner, record.module);
    if (new Set(scope.model.contract.units.map((u) => goPackage(scope.model.contract, u.module))).has(pkg)) throw new Unsupported(`${library}.${record.id}: the Go package ${pkg} of the record has the name of a package of ${scope.model.contract.library} (GN-15f)`);
    (scope.foreignImports ??= new Map()).set(goImport(owner, record.module), pkg);
    return `${pkg}.${goName(record.name)}`;
  }
  const unit = unitOf(scope.model, type);
  if (unit?.kind === 'enum' || unit?.kind === 'record' || unit?.kind === 'variant') return goUnitName(scope, unit);
  throw new Unsupported(`the type ${JSON.stringify(type)} is not generated for Go yet`);
}

// GN-16: whether the Go form of a tuple is an array, which holds parts of one Go type.
const tupleArray = (parts: string[]): boolean => parts.length > 0 && parts.every((t) => t === parts[0]);

// GN-16: whether a tuple type is a Go array, else a Tuple<N> of its parts.
export const goTupleArray = (scope: GoScope, parts: Type[]): boolean => tupleArray(parts.map((t) => goType({ ...scope, imports: new Set() }, t)));

// GN-16: the arities of the tuples of different part types in the types of the model, for the Tuple<N> of binding.
function tupleArities(model: Model): number[] {
  const found = new Set<number>();
  const scope: GoScope = { model, module: '', imports: new Set() };
  const visit = (type: Type): void => {
    if (typeof type === 'string') return;
    if ('tuple' in type) {
      type.tuple.forEach(visit);
      if (!goTupleArray(scope, type.tuple)) found.add(type.tuple.length);
      return;
    }
    for (const key of ['list', 'optional', 'map', 'keyed_map'] as const) if (key in type) visit((type as Record<string, Type>)[key] as Type);
  };
  for (const fn of callablesOf(model)) {
    for (const p of fn.params) visit(p.type);
    // A tuple return is several results; a tuple inside it is a value.
    if (typeof fn.returns === 'object' && 'tuple' in fn.returns) fn.returns.tuple.forEach(visit);
    else visit(fn.returns);
    if (fn.yields !== undefined) [fn.yields.value, ...(fn.yields.key === undefined ? [] : [fn.yields.key])].forEach(visit);
  }
  for (const unit of [...model.records, ...model.variants.flatMap((v) => v.cases.map((c) => c.unit))]) for (const f of unit.fields ?? []) visit(f.type);
  for (const cb of model.callbacks) for (const m of cb.members) [...m.params.map((p) => p.type), m.returns].forEach(visit);
  return [...found].sort((a, b) => a - b);
}

// GN-16: the struct of a tuple of n parts of different types, its parts the fields P0 to P<n-1>.
function goTupleType(n: number): string {
  const names = Array.from({ length: n }, (_, i) => `T${i}`);
  return `
// Tuple${n} is a tuple of ${n} parts of different types (GN-16), its parts in order.
type Tuple${n}[${names.join(', ')} any] struct {
${names.map((name, i) => `\tP${i} ${name}`).join('\n')}
}
`;
}

// GN-15e: whether the Go type of the type is a pointer whose nil is no value of the type, so that nil is the missing
// value of its optional and of its place with a default: a map, a keyed map, an instance of a class and a value
// class of another repository. The nil of an optional is a value of the type, so an optional is none.
export function nilAbsent(model: Model, type: Type): boolean {
  if (typeof type === 'object' && ('map' in type || 'keyed_map' in type)) return true;
  if (typeof type === 'object' && ('list' in type || 'optional' in type || 'tuple' in type)) return false;
  const alias = aliasOf(model, type);
  return alias === undefined ? objectUnit(model, type) !== undefined : alias.owner !== undefined;
}

// The part i of a Go tuple: an item of its array or a field of its struct.
const tuplePart = (scope: GoScope, parts: Type[], expr: string, i: number): string => (goTupleArray(scope, parts) ? `${expr}[${i}]` : `${expr}.P${i}`);

// U-2, T-4: a field with a default is a pointer, nil when the caller leaves it out.
export const fieldType = (scope: GoScope, field: { type: Type; default?: Default }): string =>
  goType(scope, fieldWire(field));
const fieldWire = (field: { type: Type; default?: Default }): Type => (pointed(field) ? { optional: field.type } : field.type);

export const pad = (text: string, width: number): string => text + ' '.repeat(Math.max(0, width - text.length));

// Whether a value of the type holds an instance of a class unit, which the call keeps alive (runtime.KeepAlive).
function holdsClass(model: Model, type: Type, seen: Set<string> = new Set()): boolean {
  if (typeof type === 'string') return false;
  if ('list' in type) return holdsClass(model, type.list, seen);
  if ('map' in type) return holdsClass(model, type.map, seen);
  if ('keyed_map' in type) return holdsClass(model, type.keyed_map, seen);
  if ('optional' in type) return holdsClass(model, type.optional, seen);
  if ('tuple' in type) return type.tuple.some((t) => holdsClass(model, t, seen));
  if (objectUnit(model, type) !== undefined) return true;
  const unit = unitOf(model, type);
  if (unit?.kind !== 'record' || libraryOf(type) !== undefined || seen.has(unit.id)) return false;
  seen.add(unit.id);
  return (unit.fields ?? []).some((f) => holdsClass(model, f.type, seen));
}

// Whether the encoding of a value of the type needs the call of package binding: a callback or a value alias in it.
function needsCall(model: Model, type: Type, seen: Set<string> = new Set()): boolean {
  if (typeof type === 'string') return false;
  if ('list' in type) return needsCall(model, type.list, seen);
  if ('map' in type) return needsCall(model, type.map, seen);
  if ('keyed_map' in type) return needsCall(model, type.keyed_map, seen);
  if ('optional' in type) return needsCall(model, type.optional, seen);
  if ('tuple' in type) return type.tuple.some((t) => needsCall(model, t, seen));
  // GN-6ae: a func is a callback of the call.
  if ('function' in type) return true;
  if ('passthrough' in type) return false;
  if (aliasOf(model, type) !== undefined || callbackOf(model, type) !== undefined) return true;
  const unit = unitOf(model, type);
  if (unit === undefined || libraryOf(type) !== undefined || (unit.kind !== 'record' && unit.kind !== 'variant') || seen.has(unit.id)) return false;
  seen.add(unit.id);
  // GN-6v: a variant needs the call when a field of one of its cases does.
  const fields = unit.kind === 'record' ? (unit.fields ?? []) : (unit.cases ?? []).flatMap((c) => c.fields);
  return fields.some((f) => needsCall(model, f.type, seen));
}

// ---- Go encoding of the arguments and decoding of the result ----

function goEncode(scope: GoScope, type: Type, expr: string, indent: number, depth: number): string[] {
  const t = '\t'.repeat(indent);
  if (typeof type === 'string') {
    const method: Record<string, string> = { bool: 'Bool', int: 'Int', int64: 'Int', uint: 'Uint', float: 'Float', text: 'Text', latin1: 'Text', bytes: 'Bytes', source: 'Bytes', path: 'Text' };
    return [`${t}enc.${method[type] ?? ''}(${expr})`];
  }
  if ('list' in type) {
    const item = `item${depth}`;
    return [`${t}enc.Len(len(${expr}))`, `${t}for _, ${item} := range ${expr} {`, ...goEncode(scope, type.list, item, indent + 1, depth + 1), `${t}}`];
  }
  if ('map' in type || 'keyed_map' in type) {
    const key = `key${depth}`;
    const entry = `entry${depth}`;
    const inner = 'map' in type ? type.map : type.keyed_map;
    return [
      `${t}enc.Len(${expr}.Len())`,
      `${t}for _, ${key} := range ${expr}.Keys() {`,
      `${t}\t${entry}, _ := ${expr}.Get(${key})`,
      `${t}\tenc.${'map' in type ? 'Text' : 'Key'}(${key})`,
      ...goEncode(scope, inner, entry, indent + 1, depth + 1),
      `${t}}`,
    ];
  }
  if ('optional' in type) {
    return [`${t}if ${expr} == nil {`, `${t}\tenc.Tag(false)`, `${t}} else {`, `${t}\tenc.Tag(true)`, ...goEncode(scope, type.optional, nilAbsent(scope.model, type.optional) ? expr : `*${expr}`, indent + 1, depth), `${t}}`];
  }
  if ('tuple' in type) return type.tuple.flatMap((part, i) => goEncode(scope, part, tuplePart(scope, type.tuple, expr, i), indent, depth));
  // GN-6ae: a func is a callback of the call, whose dispatch decodes the arguments, a class argument as a new
  // instance, and calls the func; a nil func is kind invalid_callback.
  if ('function' in type && !machineFunction(type)) {
    // GN-6z: a func that the core may keep is a func of the call until the C ABI reads it, and package binding holds
    // it from then on. Its dispatch decodes the arguments, calls the func and encodes its result; the error of the
    // func is the error of the dispatch. A nil func is kind invalid_argument_type. The dispatch runs in a call of its
    // own, which its parameter call names, so a result that the static library reads through a call (a value alias)
    // is encoded in that call and not in the call of the member, which may have ended.
    const parts = type.function.parameters;
    const returns = type.function.returns;
    const args = parts.map((_part, i) => `arg${i}`).join(', ');
    return [
      `${t}if ${expr} == nil {`,
      `${t}\tenc.Tag(false)`,
      `${t}} else {`,
      `${t}\tenc.Tag(true)`,
      `${t}\tcall.Keep(enc, func(call *binding.Call, dec *binding.Reader, enc *binding.Writer) error {`,
      ...parts.flatMap((part, i) => [`${t}\t\tvar arg${i} ${goType(scope, part)}`, ...goDecode(scope, part, `arg${i}`, indent + 2, depth)]),
      `${t}\t\tif err := dec.Finish(); err != nil {`,
      `${t}\t\t\treturn err`,
      `${t}\t\t}`,
      ...(returns === 'none' ? [`${t}\t\treturn ${expr}(${args})`] : [
        `${t}\t\treturned, err := ${expr}(${args})`,
        `${t}\t\tif err != nil {`,
        `${t}\t\t\treturn err`,
        `${t}\t\t}`,
        ...goEncode(scope, returns, 'returned', indent + 2, depth),
        `${t}\t\treturn nil`,
      ]),
      `${t}\t})`,
      `${t}}`,
    ];
  }
  if ('function' in type) {
    const parts = type.function.parameters;
    return [
      `${t}if ${expr} == nil {`,
      `${t}\tenc.Tag(false)`,
      `${t}} else {`,
      `${t}\tenc.Tag(true)`,
      `${t}\tcall.Callback(enc, binding.Function(func(dec *binding.Reader) (any, error) {`,
      ...parts.flatMap((part, i) => [`${t}\t\tvar arg${i} ${goType(scope, part)}`, ...goDecode(scope, part, `arg${i}`, indent + 2, depth)]),
      `${t}\t\tif err := dec.Finish(); err != nil {`,
      `${t}\t\t\treturn nil, err`,
      `${t}\t\t}`,
      `${t}\t\treturn ${expr}(${parts.map((_part, i) => `arg${i}`).join(', ')})`,
      `${t}\t}))`,
      `${t}}`,
    ];
  }
  // U-7: a value of an alias is the call that walks it and its first level.
  if (aliasOf(scope.model, type) !== undefined) return [`${t}call.Value(enc, ${expr})`];
  // T-5: an instance is the handle of its value; nil and the zero value are handle 0.
  const object = objectUnit(scope.model, type);
  if (object !== undefined) {
    const pkg = reached(scope, object.unit);
    return [`${t}enc.Uint(${pkg === undefined ? `${expr}.handle()` : `${pkg}.${goName(object.unit.name)}Handle(binding.Token{}, ${expr})`})`];
  }
  // GN-6ap: a value of a generated interface is encoded by the function of its package.
  const iface = interfaceOf(scope.model, type);
  if (iface !== undefined) return [`${t}encode${interfacePackage(scope, iface)}(enc, ${expr})`];
  // U-3: a callback is the call and its index in it; a nil interface is kind invalid_callback.
  const callback = callbackOf(scope.model, type);
  if (callback !== undefined) {
    // GN-6s: the dispatch of a callback unit of another repository is a function of this package.
    if (callback.library !== undefined) (scope.foreignCallbacks ??= new Set()).add(callback);
    const pkg = callback.library === undefined ? reached(scope, callback.unit) : undefined;
    const dispatch = pkg === undefined ? `dispatch${goName(callback.unit.name)}(${expr})` : `${pkg}.Dispatch${goName(callback.unit.name)}(binding.Token{}, ${expr})`;
    return [`${t}if ${expr} == nil {`, `${t}\tenc.Tag(false)`, `${t}} else {`, `${t}\tenc.Tag(true)`, `${t}\tcall.Callback(enc, ${dispatch})`, `${t}}`];
  }
  const unit = unitOf(scope.model, type);
  if (unit?.kind === 'enum') return [`${t}enc.Text(string(${expr}))`];
  // A field of what a pointer points to is selected through the pointer in parentheses: `*value.Field` is the pointer of
  // the field.
  if (unit?.kind === 'record') return (unit.fields ?? []).flatMap((f) => goEncode(scope, fieldWire(f), `${expr.startsWith('*') ? `(${expr})` : expr}.${goName(f.name)}`, indent, depth));
  // T-9, GN-6v: a variant, which may hold itself, is encoded by the function of its package.
  const variant = variantOf(scope.model, type);
  // A variant that holds a value alias or a callback passes the call of the member on (GN-6v).
  if (variant !== undefined) return [`${t}${variantCall(scope, variant, 'encode', `${needsCall(scope.model, type) ? 'call, ' : ''}enc, ${expr}`)}`];
  throw new Unsupported(`no Go encoding of ${JSON.stringify(type)}`);
}

export function goDecode(scope: GoScope, type: Type, target: string, indent: number, depth: number): string[] {
  const t = '\t'.repeat(indent);
  if (typeof type === 'string') {
    const method: Record<string, string> = { bool: 'Bool', int: 'Int', int64: 'Int', uint: 'Uint', float: 'Float', text: 'Text', latin1: 'Text', bytes: 'Bytes', source: 'Bytes', path: 'Text' };
    return [`${t}${target} = dec.${method[type] ?? ''}()`];
  }
  if ('list' in type) {
    const index = `i${depth}`;
    return [
      `${t}${target} = make(${goType(scope, type)}, dec.Len())`,
      `${t}for ${index} := range ${target} {`,
      ...goDecode(scope, type.list, `${target}[${index}]`, indent + 1, depth + 1),
      `${t}}`,
    ];
  }
  if ('map' in type || 'keyed_map' in type) {
    const index = `i${depth}`;
    const count = `n${depth}`;
    const entry = `entry${depth}`;
    const inner = 'map' in type ? type.map : type.keyed_map;
    return [
      `${t}${target} = &${'map' in type ? 'Map' : 'KeyedMap'}[${goType(scope, inner)}]{}`,
      `${t}for ${index}, ${count} := 0, dec.Len(); ${index} < ${count}; ${index}++ {`,
      `${t}\tkey${depth} := dec.${'map' in type ? 'Text' : 'Key'}()`,
      `${t}\tvar ${entry} ${goType(scope, inner)}`,
      ...goDecode(scope, inner, entry, indent + 1, depth + 1),
      `${t}\t${target}.Set(key${depth}, ${entry})`,
      `${t}}`,
    ];
  }
  if ('optional' in type) {
    const value = `present${depth}`;
    return [
      `${t}if dec.Tag() {`,
      `${t}\tvar ${value} ${goType(scope, type.optional)}`,
      ...goDecode(scope, type.optional, value, indent + 1, depth + 1),
      `${t}\t${target} = ${nilAbsent(scope.model, type.optional) ? '' : '&'}${value}`,
      `${t}}`,
    ];
  }
  if ('tuple' in type) return type.tuple.flatMap((part, i) => goDecode(scope, part, tuplePart(scope, type.tuple, target, i), indent, depth));
  // GN-6ae: a result passthrough is the value under its handle, which leaves the table of package binding.
  if ('passthrough' in type) return [`${t}${target} = dec.Passed()`];
  // U-7: a value of an alias is the Go value that its out rows make.
  const valueAlias = aliasOf(scope.model, type);
  // GN-6x: package binding makes the instance of a value class of another repository; a failed result is nil.
  if (valueAlias?.owner !== undefined) return [`${t}${target}, _ = dec.Value().(${goType(scope, type)})`];
  if (valueAlias !== undefined) {
    const instances = aliasInstances(scope.model, valueAlias);
    if (instances.length === 0) return [`${t}${target} = dec.Value()`];
    // GN-15c: only the package of a class makes its instance, as aliasInstance of that package.
    for (const object of instances) sameModule(scope, object.unit, `class whose instance an out row of the alias ${valueAlias.unit.id} makes`);
    for (const object of instances) (scope.aliasInstances ??= new Set()).add(object);
    return [`${t}${target} = dec.ValueWith(aliasInstance)`];
  }
  const object = objectUnit(scope.model, type);
  if (object !== undefined) {
    const pkg = reached(scope, object.unit);
    return [`${t}${target} = ${pkg === undefined ? `new${goName(object.unit.name)}(dec.Uint())` : `${pkg}.${goName(object.unit.name)}FromHandle(binding.Token{}, dec.Uint())`}`];
  }
  const unit = unitOf(scope.model, type);
  if (unit?.kind === 'enum') return [`${t}${target} = ${goUnitName(scope, unit)}(dec.Text())`];
  if (unit?.kind === 'record') return (unit.fields ?? []).flatMap((f) => goDecode(scope, fieldWire(f), `${target}.${goName(f.name)}`, indent, depth));
  // T-9, GN-6v: a variant, which may hold itself, is decoded by the function of its package.
  const variant = variantOf(scope.model, type);
  if (variant !== undefined) return [`${t}${target} = ${variantCall(scope, variant, 'decode', 'dec')}`];
  throw new Unsupported(`no Go decoding of ${JSON.stringify(type)}`);
}

// E-7: the results of a function: the parts of a tuple return, then error.
export function goResults(scope: GoScope, returns: Type): string[] {
  if (returns === 'none' || returns === 'never') return [];
  if (typeof returns === 'object' && 'tuple' in returns) return returns.tuple.map((t) => goType(scope, t));
  return [goType(scope, returns)];
}

// U-2: a parameter with a default is a pointer, nil when the caller leaves it out.
const hasDefault = (fn: Fn, parameter: Fn['params'][number]): boolean => pointed(parameter) && fn.record?.param !== parameter;
const paramType = (scope: GoScope, fn: Fn, parameter: Fn['params'][number]): string =>
  goType(scope, paramWire(fn, parameter));
const paramWire = (fn: Fn, parameter: Fn['params'][number]): Type => (hasDefault(fn, parameter) ? { optional: parameter.type } : parameter.type);

// The results of a member: an iterate gives an iterator over its items (N-4), any other member the results of its
// return (E-7).
function memberResults(scope: GoScope, fn: Fn): string[] {
  if (fn.kind !== 'iterate') return goResults(scope, fn.returns);
  scope.usesIter = true;
  const yields = fn.yields ?? { value: 'none' };
  return [yields.key === undefined ? `iter.Seq[${goType(scope, yields.value)}]` : `iter.Seq2[${goType(scope, yields.key)}, ${goType(scope, yields.value)}]`];
}

// The count of the results of a member in Go before its error: 1 for an iterate, the parts of a tuple, 0 for none and
// never.
export const goResultCount = (fn: Fn): number => {
  if (fn.kind === 'iterate') return 1;
  if (fn.returns === 'none' || fn.returns === 'never') return 0;
  return typeof fn.returns === 'object' && 'tuple' in fn.returns ? fn.returns.tuple.length : 1;
};

function goCallable(scope: GoScope, fn: Fn): string {
  const model = scope.model;
  const params = fn.params.map((p) => `${goParam(p.name, scope.model)} ${paramType(scope, fn, p)}`).join(', ');
  const results = memberResults(scope, fn);
  const signature = results.length === 0 ? 'error' : `(${[...results, 'error'].join(', ')})`;
  const zero = results.map((_, i) => `zero${i}`);
  const fail = (err: string): string => `return ${[...zero, err].join(', ')}`;
  const lines: string[] = [];
  results.forEach((type, i) => lines.push(`\tvar zero${i} ${type}`));
  if (fn.params.some((p) => needsCall(model, p.type))) lines.push('\tcall := binding.NewCall()', '\tdefer call.Close()');
  lines.push('\tenc := binding.NewWriter()');
  if (fn.receiver !== undefined) lines.push('\tenc.Uint(this.handle())');
  for (const parameter of fn.params) lines.push(...goEncode(scope, paramWire(fn, parameter), goParam(parameter.name, scope.model), 1, 0));
  lines.push(`\tdec, err := binding.${bindingFn(fn)}(enc.Done())`);
  // T-5: an instance stays reachable until the call has taken its value, so the runtime does not release it during
  // the call.
  const alive = [...(fn.receiver === undefined ? [] : ['this']), ...fn.params.filter((p) => holdsClass(model, p.type)).map((p) => goParam(p.name, scope.model))];
  for (const value of alive) lines.push(`\truntime.KeepAlive(${value})`);
  if (alive.length > 0) scope.usesRuntime = true;
  lines.push('\tif err != nil {', `\t\t${fail('err')}`, '\t}');
  if (fn.kind === 'iterate') {
    // N-4 iterate: the items are converted when the call returns, and the iterator gives them in order.
    const yields = fn.yields ?? { value: 'none' };
    lines.push('\tn := dec.Len()');
    if (yields.key !== undefined) lines.push(`\tkeys := make([]${goType(scope, yields.key)}, n)`);
    lines.push(`\tvalues := make([]${goType(scope, yields.value)}, n)`, '\tfor at := range n {');
    if (yields.key !== undefined) lines.push(...goDecode(scope, yields.key, 'keys[at]', 2, 0));
    lines.push(...goDecode(scope, yields.value, 'values[at]', 2, 0), '\t}');
    lines.push('\tif err := dec.Finish(); err != nil {', `\t\t${fail('err')}`, '\t}');
    const yieldType = yields.key === undefined ? `func(${goType(scope, yields.value)}) bool` : `func(${goType(scope, yields.key)}, ${goType(scope, yields.value)}) bool`;
    lines.push(
      `\treturn func(yield ${yieldType}) {`,
      '\t\tfor at := range values {',
      `\t\t\tif !yield(${yields.key === undefined ? '' : 'keys[at], '}values[at]) {`,
      '\t\t\t\treturn',
      '\t\t\t}',
      '\t\t}',
      '\t}, nil',
    );
  } else {
    const parts = typeof fn.returns === 'object' && 'tuple' in fn.returns ? fn.returns.tuple : fn.returns === 'none' || fn.returns === 'never' ? [] : [fn.returns];
    parts.forEach((type, i) => {
      lines.push(`\tvar value${i} ${results[i] ?? ''}`);
      lines.push(...goDecode(scope, type, `value${i}`, 1, 0));
    });
    lines.push('\tif err := dec.Finish(); err != nil {', `\t\t${fail('err')}`, '\t}', `\treturn ${[...parts.map((_, i) => `value${i}`), 'nil'].join(', ')}`);
  }
  const className = goName(fn.unit.name);
  const name = goMemberName(fn);
  if (fn.kind === 'function' || fn.kind === 'constructor' || fn.kind === 'static') {
    return `
// ${name} calls ${fn.corePath} (contract member ${fn.member.id}).${internalDoc(scope.model, fn.unit)}
func ${name}(${params}) ${signature} {
${lines.join('\n')}
}
`;
  }
  if (fn.special === 'to_json') {
    // GN-15a: json.Marshal of an instance calls MarshalJSON, which marshals the value of the core.
    const marshal = results.length === 0
      ? '\treturn nil, this.toJSON()'
      : '\tvalue, err := this.toJSON()\n\tif err != nil {\n\t\treturn nil, err\n\t}\n\treturn json.Marshal(value)';
    if (results.length > 0) scope.usesJson = true;
    return `
// toJSON calls ${fn.corePath} (contract member ${fn.member.id}).
func (this *${className}) toJSON() ${signature} {
${lines.join('\n')}
}

// MarshalJSON is the JSON form of the ${className} (N-4: to_json), which encoding/json calls through json.Marshaler.
func (this *${className}) MarshalJSON() ([]byte, error) {
${marshal}
}
`;
  }
  if (fn.special === 'stringify') {
    return `
// stringify calls ${fn.corePath} (contract member ${fn.member.id}).
func (this *${className}) stringify() ${signature} {
${lines.join('\n')}
}

// String is the text of the ${className} (N-4: stringify). fmt.Stringer has no error result, so a failure of the core
// panics with its error.${internalDoc(scope.model, fn.unit)}
func (this *${className}) String() string {
	text, err := this.stringify()
	if err != nil {
		panic(err)
	}
	return text
}
`;
  }
  return `
// ${name} calls ${fn.corePath} (contract member ${fn.member.id}).${internalDoc(scope.model, fn.unit)}
func (this *${className}) ${name}(${params}) ${signature} {
${lines.join('\n')}
}
`;
}

// GN-6r: the doc comment of a declaration of an internal unit ends with the sentence that it is no public API, because
// Go has no marker of an exported name that only one module uses.
const internalDoc = (model: Model, unit: Unit): string => (isInternal(unit) ? `\n// It is internal to ${model.contract.library} (U-1) and is no public API.` : '');

function goConstant(model: Model, c: Constant): string {
  const name = langName('go', c.member.name, 'constant');
  const type: Record<string, string> = { uint: 'uint64', int: 'int64', text: 'string', bool: 'bool' };
  const value = c.member.type === 'text' ? goString(String(c.member.value)) : String(c.member.value);
  return `
// ${name} is the constant ${c.member.core as string} of the core (U-5).${internalDoc(model, c.unit)}
const ${name} ${type[c.member.type as string] ?? ''} = ${value}
`;
}

function goEnum(model: Model, unit: Unit): string {
  const name = goName(unit.name);
  const variants = (unit.variants ?? []).map((v) => ({ id: `${name}${goName(v.name)}`, value: v.value }));
  const width = Math.max(...variants.map((v) => v.id.length));
  return `
// ${name} is the enum ${unit.id} (T-6): a typed string whose values are the constants below.${internalDoc(model, unit)}
type ${name} string

// The values of ${name}.${internalDoc(model, unit)}
const (
${variants.map((v) => `\t${pad(v.id, width)} ${name} = ${goString(v.value)}`).join('\n')}
)
`;
}

// GN-6ap: the name of a generated interface for its type and its encode function, which is unexported, as its method
// is, so a package of another module does not reach them.
function interfacePackage(scope: GoScope, iface: Unit): string {
  if (iface.module !== scope.module) throw new Unsupported(`${iface.id}: a generated interface of the module ${iface.module || '(the root)'} in the module ${scope.module || '(the root)'} is not generated for Go yet (its method and its encode function are unexported) (GN-6ap)`);
  return goName(iface.name);
}

// GN-6ap: a generated interface is a Go interface whose one method is unexported, so that only the classes of its
// package that the contract names implement it; the method gives the position of the class and the handle.
function goInterface(model: Model, iface: Unit): string {
  const name = goName(iface.name);
  const classes = implementorsOf(model, iface);
  const outside = classes.find((o) => o.unit.module !== iface.module);
  if (outside !== undefined) throw new Unsupported(`${outside.unit.id}: a class of the module ${outside.unit.module || '(the root)'} that implements the generated interface ${iface.id} of the module ${iface.module || '(the root)'} is not generated for Go yet (the method of the interface is unexported) (GN-6ap)`);
  return `
// ${name} is the interface ${iface.id} (GN-6ap): a parameter of it takes ${classes.map((o) => `a *${goName(o.unit.name)}`).join(' or ')}. Only the classes that the
// contract names implement it.${internalDoc(model, iface)}
type ${name} interface {
	// implements${name} gives the position of the class among the classes that implement ${name}, from 1, and the handle
	// of the value.
	implements${name}() (uint64, uint64)
}

// encode${name} encodes the position of the class of value and the handle of its value; a nil interface is position 0,
// which the binding refuses with kind invalid_argument_type.
func encode${name}(enc *binding.Writer, value ${name}) {
	if value == nil {
		enc.Uint(0)
		enc.Uint(0)
		return
	}
	class, handle := value.implements${name}()
	enc.Uint(class)
	enc.Uint(handle)
}
${classes.map((o, i) => `
// implements${name} makes *${goName(o.unit.name)} a ${name} (GN-6ap).
func (this *${goName(o.unit.name)}) implements${name}() (uint64, uint64) { return ${i + 1}, this.handle() }

var _ ${name} = (*${goName(o.unit.name)})(nil)
`).join('')}`;
}

// GN-6w: the pointer to a class that implements callback interfaces has their methods, which the compiler checks.
function goImplements(scope: GoScope, object: ObjectClass): string {
  const name = goName(object.unit.name);
  return (object.unit.implements ?? []).map((ref) => {
    // GN-6ap: the method of a generated interface is written with the interface.
    if (scope.model.interfaces.some((i) => i.id === ref.unit)) return '';
    const callback = scope.model.callbacks.find((c) => c.unit.id === ref.unit);
    if (callback === undefined) throw new Unsupported(`${object.unit.id}: implements ${ref.unit}, which is no callback interface of this contract (U-1)`);
    return `
// ${name} implements ${goName(callback.unit.name)} (GN-6w): an instance stands where the callback is taken.
var _ ${goUnitName(scope, callback.unit)} = (*${name})(nil)
`;
  }).join('');
}

// T-9, GN-6v: the call of the encode or decode function of a variant with its arguments. Those functions are
// unexported; a package of another module calls the exported Encode<Name> or Decode<Name> of the package of the
// variant, which binding.Token keeps out of the reach of other code (GN-15a).
function variantCall(scope: GoScope, variant: Variant, which: 'encode' | 'decode', args: string): string {
  const name = goName(variant.unit.name);
  const pkg = reached(scope, variant.unit);
  if (pkg === undefined) return `${which}${name}(${args})`;
  return `${pkg}.${which === 'encode' ? 'Encode' : 'Decode'}${name}(binding.Token{}, ${args})`;
}

// GN-15a: the functions through which another module encodes and decodes a variant of this package.
function goReachableVariant(scope: GoScope, variant: Variant): string {
  const name = goName(variant.unit.name);
  const withCall = needsCall(scope.model, { unit: variant.unit.id });
  return `
// Encode${name} encodes a ${name} for a call of another module of the binding (GN-15a).
func Encode${name}(_ binding.Token, ${withCall ? 'call *binding.Call, ' : ''}enc *binding.Writer, value ${name}) {
	encode${name}(${withCall ? 'call, ' : ''}enc, value)
}

// Decode${name} decodes a ${name} for a call of another module of the binding (GN-15a).
func Decode${name}(_ binding.Token, dec *binding.Reader) ${name} {
	return decode${name}(dec)
}
`;
}

// T-9, GN-6v: a variant is an interface whose one method is unexported, so that only its case structs implement it,
// and each case a struct of its fields that implements it with a value receiver.
function goVariant(scope: GoScope, variant: Variant): string {
  const name = goName(variant.unit.name);
  const cases = variant.cases.map((kase) => {
    const caseType = goName(kase.unit.name);
    const fields = (kase.unit.fields ?? []).map((f) => ({ name: goName(f.name), type: goType(scope, f.type) }));
    const width = Math.max(0, ...fields.map((f) => f.name.length));
    const left = (kase.unit.fields ?? []).some((f) => f.default !== undefined) ? ' A field that may be left out is nil when it is (T-4).' : '';
    return `
// ${caseType} is the case ${kase.value} of the variant ${name} (T-9).${left}
type ${caseType} struct${fields.length === 0 ? '{}' : ` {\n${fields.map((f) => `\t${pad(f.name, width)} ${f.type}`).join('\n')}\n}`}

func (${caseType}) is${name}() {}
`;
  }).join('');
  const named = variant.cases.some((kase) => (kase.unit.fields ?? []).length > 0);
  const encode = variant.cases.flatMap((kase, number) => [
    `\tcase ${goName(kase.unit.name)}:`,
    `\t\tenc.Uint(${number})`,
    ...(kase.unit.fields ?? []).flatMap((f) => goEncode(scope, f.type, `case0.${goName(f.name)}`, 2, 1)),
  ]);
  const decode = variant.cases.flatMap((kase, number) => {
    const fields = kase.unit.fields ?? [];
    return [
      `\tcase ${number}:`,
      ...(fields.length === 0
        ? [`\t\tvalue = ${goName(kase.unit.name)}{}`]
        : [`\t\tvar case0 ${goName(kase.unit.name)}`, ...fields.flatMap((f) => goDecode(scope, f.type, `case0.${goName(f.name)}`, 2, 1)), '\t\tvalue = case0']),
    ];
  });
  const withCall = needsCall(scope.model, { unit: variant.unit.id });
  return `
// ${name} is the variant ${variant.unit.id} (T-9): a value is one of its case structs, ${variant.cases.map((kase) => goName(kase.unit.name)).join(', ')}.
type ${name} interface {
	is${name}()
}
${cases}
// encode${name} encodes a ${name}: the number of its case in the contract and the fields of the case; a value that is
// no case struct, nil or a pointer to a case struct, is the number 2^64 - 1, which the static library refuses (GN-6v).${withCall ? `
// A value alias in a case is walked by the call of the member that takes the ${name}.` : ''}
func encode${name}(${withCall ? 'call *binding.Call, ' : ''}enc *binding.Writer, value ${name}) {
	switch ${named ? 'case0 := ' : ''}value.(type) {
${encode.join('\n')}
	default:
		enc.Uint(^uint64(0))
	}
}

// decode${name} decodes a ${name} from the number of its case and its fields (GN-6v).
func decode${name}(dec *binding.Reader) ${name} {
	var value ${name}
	switch dec.Case(${variant.cases.length}) {
${decode.join('\n')}
	}
	return value
}
`;
}

function goRecord(scope: GoScope, unit: Unit): string {
  const name = goName(unit.name);
  const fields = (unit.fields ?? []).map((f) => ({ name: goName(f.name), type: fieldType(scope, f) }));
  const width = Math.max(...fields.map((f) => f.name.length));
  const defaults = (unit.fields ?? []).some((f) => f.default !== undefined) ? ' A field that is a pointer has a default: nil leaves it to\n// the core (U-2).' : '';
  return `
// ${name} is the record ${unit.id} (T-4): the last argument of the functions that take it, and a result.${defaults}${internalDoc(scope.model, unit)}
type ${name} struct {
${fields.map((f) => `\t${pad(f.name, width)} ${f.type}`).join('\n')}
}
`;
}

// T-5: a class unit is a struct around the handle of its value in the static library, which the binding releases when
// the Go runtime finds the instance unreachable (runtime.AddCleanup).
function goClass(model: Model, unit: Unit): string {
  const name = goName(unit.name);
  return `
// ${name} is the class ${unit.id} (T-5): it holds a value of ${unit.core_type ?? ''} in the static library, which
// the binding releases when the Go runtime finds the ${name} unreachable. nil and the zero value hold no value: a call
// that takes one fails with kind invalid_argument_type.${internalDoc(model, unit)}
type ${name} struct{ ref *binding.Ref }

// new${name} holds the value under the handle that a call gave.
func new${name}(handle uint64) *${name} {
	return &${name}{ref: binding.NewRef(handle, binding.${releaseFn(unit)})}
}

// handle is the handle of the value, 0 for nil and for the zero value.
func (this *${name}) handle() uint64 {
	if this == nil || this.ref == nil {
		return 0
	}
	return this.ref.Handle()
}
`;
}

// GN-6s: a callback unit of another repository is the Go interface of the package of its module in the Go module of that
// repository, which go.mod requires; a user implements that interface.
function foreignCallbackType(scope: GoScope, cb: CallbackUnit): string {
  const owner = cb.library === undefined ? undefined : scope.model.foreign.get(cb.library);
  if (owner === undefined || cb.library === undefined) throw new Unsupported(`${cb.unit.id}: the contract of the library of the callback unit is not found (GN-6s)`);
  const pkg = goPackage(owner, cb.unit.module);
  if (new Set(scope.model.contract.units.map((u) => goPackage(scope.model.contract, u.module))).has(pkg)) throw new Unsupported(`${cb.library}.${cb.unit.id}: the Go package ${pkg} of the callback unit has the name of a package of ${scope.model.contract.library} (GN-6s)`);
  (scope.foreignImports ??= new Map()).set(goImport(owner, cb.unit.module), pkg);
  return `${pkg}.${goName(cb.unit.name)}`;
}

