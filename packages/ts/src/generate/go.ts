// GN-15f: the Go module of a contract. The contract of a generated Go binding has one (CK-1); the contract of another
// library whose record or value class the binding names may have none, which refuses the Go target with its sentence.
export const goModule = (contract: Contract): string => {
  const module = (contract.packages['go'] as { module?: string } | undefined)?.module;
  if (module === undefined) throw new Unsupported(`${contract.library}: the library has no Go module (packages.go), whose record or value class the Go binding names (GN-15f)`);
  return module;
};

// P-2: the Go package of a module is packages/go/<module>; its import path is the Go module path and the module.
export const goDir = (module: string): string => (module === '' ? GO : `${GO}/${module}`);
export const goImport = (contract: Contract, module: string): string => (module === '' ? goModule(contract) : `${goModule(contract)}/${module}`);

// The package name: the last segment of the module in lower case without separators, and for the empty module the
// repository name without - (P-1; the last element of the import path, go, cannot be an identifier, and Go allows a
// package name that differs from it).
export function goPackage(contract: Contract, module: string): string {
  const base = module === '' ? libraryParts(contract).repository : (module.split('/').at(-1) ?? module);
  return base.toLowerCase().replace(/[^a-z0-9]/g, '');
}

