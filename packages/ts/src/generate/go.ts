// GN-6s: whether a member of a callback unit of another repository recognizes an error unit of its owner.
const recognizesOwner = (model: Model): boolean => model.foreignCallbacks.some((c) => c.members.some((m) => m.recognized !== undefined));

// GN-6s, GN-15d: the name of the package errors of the Go module of another repository, which the package imports.
export function ownerErrors(scope: GoScope, library: string): string {
  const owner = scope.model.foreign.get(library);
  if (owner === undefined) throw new Unsupported(`${library}: the contract of the library is not found (GN-6s)`);
  const name = `${goPackage(owner, '')}errors`;
  (scope.foreignErrors ??= new Map()).set(goImport(owner, 'errors'), name);
  return name;
}

// U-3: the methods of a callback unit in Go and the cases of its dispatch, one per member.
function callbackCases(scope: GoScope, cb: CallbackUnit): { methods: { m: CallbackMember; method: string; params: string; signature: string }[]; cases: string[] } {
  const methods = cb.members.map((m) => {
    const method = langName('go', m.member.name, 'callable');
    const params = m.params.map((p) => `${goParam(p.name, scope.model)} ${goType(scope, p.type)}`).join(', ');
    const results = goResults(scope, m.returns);
    return { m, method, params, signature: results.length === 0 ? 'error' : `(${[...results, 'error'].join(', ')})` };
  });
  const cases = methods.map(({ m, method }, index) => {
    const lines: string[] = [`\t\tcase ${index}:`];
    for (const p of m.params) {
      lines.push(`\t\t\tvar ${goParam(p.name, scope.model)} ${goType(scope, p.type)}`);
      lines.push(...goDecode(scope, p.type, goParam(p.name, scope.model), 3, 0));
    }
    lines.push('\t\t\tif err := dec.Finish(); err != nil {', '\t\t\t\treturn err', '\t\t\t}');
    const args = m.params.map((p) => goParam(p.name, scope.model)).join(', ');
    // U-3, GN-6d: an error of a unit that the member recognizes goes to the core with its kind and its message.
    const failed = (m.recognized?.units ?? []).reduce((err, u) => (cb.library === undefined ? `binding.Recognize${goName(u.unit.name)}(${err})` : `binding.RecognizeAs[*${ownerErrors(scope, cb.library)}.${goName(u.unit.name)}](${err})`), 'err');
    if (m.returns === 'none' && m.recognized === undefined) {
      lines.push(`\t\t\treturn object.${method}(${args})`);
    } else if (m.returns === 'none') {
      lines.push(`\t\t\tif err := object.${method}(${args}); err != nil {`, `\t\t\t\treturn ${failed}`, '\t\t\t}', '\t\t\treturn nil');
    } else {
      lines.push(`\t\t\treturned, err := object.${method}(${args})`, '\t\t\tif err != nil {', `\t\t\t\treturn ${failed}`, '\t\t\t}');
      lines.push(...goEncode(scope, m.returns, 'returned', 3, 0), '\t\t\treturn nil');
    }
    return lines.join('\n');
  });
  return { methods, cases };
}

// U-3: a callback unit is a Go interface, and its dispatch runs a member for the core with the decoded arguments.
function goCallback(scope: GoScope, cb: CallbackUnit): string {
  const name = goName(cb.unit.name);
  const { methods, cases } = callbackCases(scope, cb);
  return `
// ${name} is the callback interface ${cb.unit.id} (U-3): Go code implements it, and the core calls its methods during
// the call that takes it, on the goroutine of that call. An error that a method returns ends that call, which returns
// the same error.${internalDoc(scope.model, cb.unit)}
type ${name} interface {
${methods.map(({ m, method, params, signature }) => `\t// ${method} is the member ${m.member.id}.\n\t${method}(${params}) ${signature}`).join('\n')}
}

${goDispatch(scope, cb, cases)}`;
}

// U-3: the dispatch of a callback, which runs a member of the object for the core with the decoded arguments.
function goDispatch(scope: GoScope, cb: CallbackUnit, cases: string[]): string {
  const name = goName(cb.unit.name);
  const type = cb.library === undefined ? name : foreignCallbackType(scope, cb);
  return `
// dispatch${name} runs a member of a ${type} for the core (U-3${cb.library === undefined ? '' : ', GN-6s'}).
func dispatch${name}(object ${type}) binding.Callback {
	return func(call *binding.Call, member uint32, dec *binding.Reader, enc *binding.Writer) error {
		switch member {
${cases.join('\n')}
		}
		return binding.Malformed()
	}
}
`;
}

// A Go interpreted string literal of UTF-8 text, with only printable ASCII in the source.
export function goString(text: string): string {
  let out = '"';
  for (const char of text) {
    const code = char.codePointAt(0) ?? 0;
    if (char === '"' || char === '\\') out += `\\${char}`;
    else if (code >= 0x20 && code < 0x7f) out += char;
    else if (code <= 0xffff) out += `\\u${code.toString(16).padStart(4, '0')}`;
    else out += `\\U${code.toString(16).padStart(8, '0')}`;
  }
  return `${out}"`;
}

// A Go interpreted string literal whose bytes are the given bytes (T-1 latin1 in Go, B-8).
export function goBytes(bytes: Iterable<number>): string {
  let out = '"';
  for (const byte of bytes) {
    const char = String.fromCharCode(byte);
    if (char === '"' || char === '\\') out += `\\${char}`;
    else if (byte >= 0x20 && byte < 0x7f) out += char;
    else out += `\\x${byte.toString(16).padStart(2, '0')}`;
  }
  return `${out}"`;
}

// The import block of a file: the standard library first, then the packages of the module, as gofmt groups them.
export function goImportBlock(std: string[], own: string[]): string {
  // gofmt sorts a group by the path, not by the name before it.
  const byPath = (a: string, b: string): number => {
    const pa = a.slice(a.indexOf('"'));
    const pb = b.slice(b.indexOf('"'));
    return pa < pb ? -1 : pa > pb ? 1 : 0;
  };
  const paths = [...[...new Set(std)].sort(byPath), ...(std.length > 0 && own.length > 0 ? [''] : []), ...[...new Set(own)].sort(byPath)];
  if (paths.length === 1) return `import ${paths[0] ?? ''}\n`;
  return `import (\n${paths.map((p) => (p === '' ? '' : `\t${p}`)).join('\n')}\n)\n`;
}

// GN-15a: the functions through which another module reaches a class or a callback of this package; binding.Token,
// which only the packages of the Go module can name, keeps them out of the reach of other code.
function goReachable(scope: GoScope, unit: Unit, callback: boolean): string {
  const name = goName(unit.name);
  if (callback) {
    return `
// Dispatch${name} is the dispatch of a ${name} for a call of another module of the binding (GN-15a).
func Dispatch${name}(_ binding.Token, object ${name}) binding.Callback {
	return dispatch${name}(object)
}
`;
  }
  return `
// ${name}Handle is the handle of a ${name} for a call of another module of the binding (GN-15a).
func ${name}Handle(_ binding.Token, this *${name}) uint64 {
	return this.handle()
}

// ${name}FromHandle holds the value under the handle that a call of another module of the binding gave (GN-15a).
func ${name}FromHandle(_ binding.Token, handle uint64) *${name} {
	return new${name}(handle)
}
`;
}

function goPackageFile(model: Model, module: string, reachedFrom: Set<string>, seen?: GoScope): string {
  const scope: GoScope = seen ?? { model, module, imports: new Set() };
  const objects = model.objects.filter((o) => o.unit.module === module);
  const callbacks = model.callbacks.filter((c) => c.unit.module === module);
  const body = [
    ...model.enums.filter((u) => u.module === module).map((u) => goEnum(model, u)),
    ...model.records.filter((u) => u.module === module).map((u) => goRecord(scope, u)),
    ...model.variants.filter((v) => v.unit.module === module).map((v) => goVariant(scope, v)),
    ...model.constants.filter((c) => c.module === module).map((c) => goConstant(model, c)),
    ...callbacks.map((c) => goCallback(scope, c)),
    ...model.functions.filter((f) => f.module === module).map((f) => goCallable(scope, f)),
    ...objects.flatMap((o) => [goClass(model, o.unit), ...o.members.map((f) => goCallable(scope, f)), goImplements(scope, o)]),
    ...model.interfaces.filter((i) => i.module === module).map((i) => goInterface(model, i)),
    ...model.kept.filter((k) => k.unit.module === module).map((k) => goKeptAlias(scope, k)),
    ...callbacks.filter((c) => reachedFrom.has(c.unit.id)).map((c) => goReachable(scope, c.unit, true)),
    ...objects.filter((o) => reachedFrom.has(o.unit.id)).map((o) => goReachable(scope, o.unit, false)),
    ...model.variants.filter((v) => v.unit.module === module && reachedFrom.has(v.unit.id)).map((v) => goReachableVariant(scope, v)),
  ].join('') + [...(scope.foreignCallbacks ?? [])].map((cb) => goDispatch(scope, cb, callbackCases(scope, cb).cases)).join('');
  const made = [...(scope.aliasInstances ?? [])].sort((a, b) => model.objects.indexOf(a) - model.objects.indexOf(b));
  const instance = made.length === 0
    ? ''
    : `
// aliasInstance makes the instance of a class of this package by its number in the contract, for a value alias whose
// out rows make an instance by a member (U-7, GN-15c); nil for any other number.
func aliasInstance(class uint64, handle uint64) any {
	switch class {
${made.map((o) => `	case ${model.objects.indexOf(o)}:
		return new${goName(o.unit.name)}(handle)`).join('\n')}
	}
	return nil
}
`;
  const usesBinding = model.functions.some((f) => f.module === module) || objects.length > 0 || model.kept.some((k) => k.unit.module === module) || model.variants.some((v) => v.unit.module === module) || callbacks.length > 0 || scope.usesMap === true || scope.usesKeyed === true || (scope.usesTuples?.size ?? 0) > 0;
  const tuples = [...(scope.usesTuples ?? [])].sort((a, b) => a - b).map((n) => {
    const names = Array.from({ length: n }, (_, i) => `T${i}`);
    return `
// Tuple${n} is a tuple of ${n} parts of different types (GN-16), its parts the fields P0 to P${n - 1} in order.
type Tuple${n}[${names.join(', ')} any] = binding.Tuple${n}[${names.join(', ')}]
`;
  }).join('');
  const alias = scope.usesMap === true
    ? `
// Map is the contract type map<T> (T-2): text keys in the order in which they were first set, each with its value. Its
// zero value is an empty map; a nil *Map is an empty map too.
type Map[T any] = binding.Map[T]
`
    : '';
  const keyed = scope.usesKeyed === true
    ? `
// KeyedMap is the contract type keyed_map<T> (T-2): keys of the kinds that the contract lists, in the order in which
// they were first set, each with its value. Its zero value is an empty map; a nil *KeyedMap is an empty map too.
type KeyedMap[T any] = binding.KeyedMap[T]

// Key is a key of a KeyedMap: an integer, a byte string or a text, which are different keys even with the same digits.
type Key = binding.Key

// IntKey is the integer key of a value.
func IntKey(value int64) Key { return binding.IntKey(value) }

// BytesKey is the byte string key of a value.
func BytesKey(value []byte) Key { return binding.BytesKey(value) }

// TextKey is the text key of a value.
func TextKey(value string) Key { return binding.TextKey(value) }
`
    : '';
  const std = [...(scope.usesJson === true ? ['"encoding/json"'] : []), ...(scope.usesIter === true ? ['"iter"'] : []), ...(scope.usesRuntime === true ? ['"runtime"'] : [])];
  const own = [...(usesBinding ? [`"${goImport(model.contract, 'internal/binding')}"`] : []), ...[...scope.imports].map((m) => `"${goImport(model.contract, m)}"`), ...[...(scope.foreignImports ?? new Map()).keys()].map((path) => `"${path}"`), ...[...(scope.foreignErrors ?? new Map<string, string>())].map(([path, name]) => `${name} "${path}"`)];
  const imports = std.length + own.length > 0 ? `\n${goImportBlock(std, own)}` : '';
  return `${goHeader()}

// Package ${goPackage(model.contract, module)} is the module ${module === '' ? '(the root)' : module} of the Go binding of ${model.contract.library}.
package ${goPackage(model.contract, module)}
${imports}${alias}${keyed}${tuples}${body}${instance}`;
}

